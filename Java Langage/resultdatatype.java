/*--------------Result Of Datatype----------------------*/
class resultdatatype{
    public static void main(String[] args){
        byte a = 11;
        int b = 12;
        short c = 17;
        int d = a + b;
        float e = 6.5f + c; 
        double f = d + e;
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
        System.out.println(c);
    }
}
